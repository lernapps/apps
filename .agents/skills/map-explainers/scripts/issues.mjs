// Turns an explainer draft (skill map-explainers) into the texts of GitHub issues, in German: one issue per explainer
// and one overview issue per subject. Prints JSON: { overview: { title, body, labels }, explainers: [{ id, title, body,
// labels }] }. The overview links the explainer issues once their numbers are known: --numbers id=12,id2=13.
// Usage: node .agents/skills/map-explainers/scripts/issues.mjs <subject> --file <draft.md> [--numbers id=n,…]
import { readFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { loadMap } from "../../../../lib/map.js";
import { parseExplainers } from "./parse.mjs";

const root = fileURLToPath(new URL("../../../../", import.meta.url));
export const LABELS = ["explainer", "proposed"];
// every text written to GitHub ends with this footer
const FOOTER = "\n\n---\n_Generated by [Claude Code](https://claude.ai/code)_";
const de = (t) => (typeof t === "string" ? t : t?.de ?? "");
const MAP = "https://lernapps.net/apps/map";

/**
 * Joins hard-wrapped lines of Markdown prose: GitHub shows every line break in an issue. A line continues the one before
 * unless it starts a list item, a table row, a heading or a quote, or follows a blank line.
 */
function unwrap(text) {
  const out = [];
  for (const line of text.split("\n")) {
    const t = line.trim();
    const starts = /^([-*+] |\d+\. |\||#|>)/.test(t);
    if (t && out.length && out.at(-1).trim() && !starts && !out.at(-1).trim().startsWith("|")) out[out.length - 1] += " " + t;
    else out.push(starts ? t : line.trimEnd());
  }
  return out.join("\n");
}

/** The text of a `## <heading>` section of the draft, without the heading; "" when missing. */
function section(text, heading) {
  const m = text.match(new RegExp(`^## ${heading}\\s*\\n([\\s\\S]*?)(?=^## |$(?![\\s\\S]))`, "m"));
  return m ? m[1].trim() : "";
}

export function issues(subject, text, numbers = new Map()) {
  const parsed = parseExplainers(text);
  const fach = de(subject.name);
  const comp = (id) => subject.competencies.get(id);
  const strandName = (id) => de(subject.strands.find((s) => s.id === id)?.name);
  const link = (id) => (comp(id) ? `[${de(comp(id).name)}](${MAP}/${subject.id}/c/${id}/)` : `\`${id}\``);
  const titleOf = (e) => `Explainer ${fach}: ${e.title}`;
  // an explainer named by its id in backticks (in Abgrenzung, Didaktik, reasons) becomes „its title“, or #n with --numbers
  const byId = new Map(parsed.explainers.map((e) => [e.id, e]));
  const chapters = new Map(parsed.explainers.flatMap((e) => e.chapters.map((c) => [c.id, c])));
  const names = (t = "") =>
    t.replace(/`([a-z0-9-]+)`/g, (m, id) =>
      byId.has(id)
        ? numbers.has(id)
          ? `#${numbers.get(id)}`
          : `„${byId.get(id).title}“`
        : chapters.has(id) && !comp(id)
          ? `„${chapters.get(id).title}“`
          : m,
    );
  const explainers = parsed.explainers.map((e) => {
    const ids = [...new Set(e.chapters.flatMap((c) => c.competencies))];
    const bands = [...new Set(e.chapters.map((c) => c.band))];
    const kind = e.target?.strand
      ? `Strang-App \`${e.target.strand}\` (Strang „${strandName(e.target.strand.split("/")[1])}“)`
      : `Einheiten-App über mehrere Stränge von ${fach}`;
    const lines = [
      `> Vorschlag für einen Explainer im Fach ${fach}, entworfen nach dem Skill \`map-explainers\` (lernapps/apps).`,
      "",
      `**Leitidee:** ${e.fields.Leitidee ?? ""}`,
      "",
      "| | |",
      "|---|---|",
      `| Explainer | ${kind} |`,
      `| Stufen | ${bands.join(", ")} |`,
      `| Kapitel · Bausteine | ${e.chapters.length} · ${ids.length} |`,
      "",
      "## Didaktik",
      names(e.fields.Didaktik),
      "",
      "## Abgrenzung",
      names(e.fields.Abgrenzung),
      "",
      "## Kapitel",
    ];
    e.chapters.forEach((c, i) => {
      lines.push("", `### ${i + 1} · ${c.title} (${c.band})`, c.core, "", `*${names(c.didactics)}*`, "", `Bausteine: ${c.competencies.map(link).join(" · ")}`);
      if (c.reason) lines.push("", `Ausnahme: ${names(c.reason)}`);
    });
    if (e.reason) lines.push("", "## Begründete Ausnahmen", names(e.reason));
    lines.push(
      "",
      "## Einordnung in die Lernlandkarte",
      `- [ ] Untersuche, wie der Explainer in die [Lernlandkarte für ${fach}](${MAP}/${subject.id}/) passt: worauf seine Bausteine aufbauen, was auf ihnen aufbaut und welche Kapitel dafür eine Sammel-Wiederholung brauchen.`,
      "",
      "## Fertig, wenn",
      `- Der Explainer ist gebaut und eingetragen; seine Seiten üben alle ${ids.length} Bausteine.`,
      "- `lernapps check` meldet keine Fehler.",
    );
    return { id: e.id, title: titleOf(e), body: lines.join("\n") + FOOTER, labels: LABELS };
  });
  const principles = section(text, "Prinzipien des Fachs");
  const without = parsed.without;
  const notes = section(text, "Hinweise zur Karte");
  const total = new Set(parsed.explainers.flatMap((e) => e.chapters.flatMap((c) => c.competencies))).size;
  const overview = [
    `> Überblick über die vorgeschlagenen Explainer im Fach ${fach}, entworfen nach dem Skill \`map-explainers\` (lernapps/apps).`,
    `> ${parsed.explainers.length} Explainer, ${parsed.explainers.reduce((n, e) => n + e.chapters.length, 0)} Kapitel, ${total} von ${subject.competencies.size} Bausteinen. [Lernlandkarte für ${fach}](${MAP}/${subject.id}/)`,
    "",
    "## Prinzipien des Fachs",
    names(unwrap(principles)),
    "",
    "## Explainer",
    ...parsed.explainers.map((e) => `- [ ] ${numbers.has(e.id) ? `#${numbers.get(e.id)}` : `\`${e.id}\``} ${e.title}`),
  ];
  if (without.length) overview.push("", "## Ohne Explainer", ...without.map((w) => `- ${link(w.id)}: ${w.reason}`));
  if (notes) overview.push("", "## Hinweise zur Karte", names(unwrap(notes)));
  return { overview: { title: `Explainer ${fach}: Überblick`, body: overview.join("\n") + FOOTER, labels: LABELS }, explainers };
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const argv = process.argv.slice(2);
  const opt = (name) => {
    const i = argv.indexOf(name);
    return i >= 0 ? argv.splice(i, 2)[1] : undefined;
  };
  const file = opt("--file");
  const numbers = new Map((opt("--numbers") ?? "").split(",").filter(Boolean).map((p) => p.split("=")).map(([k, v]) => [k, Number(v)]));
  const subject = loadMap(root + "map").find((s) => s.id === argv[0]);
  if (!subject || !file) {
    console.error("usage: issues.mjs <subject> --file <draft.md> [--numbers id=n,…]");
    process.exit(2);
  }
  console.log(JSON.stringify(issues(subject, readFileSync(file, "utf8"), numbers), null, 2));
}
